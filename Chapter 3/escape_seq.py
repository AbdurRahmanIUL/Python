# Escape Sequence Characters

# Sequence of characters after backslash "\" are called Escape Sequence characters.
# These characters represent one special character inside strings.

#\n: backslash n makes a new line after writing \n
a = "I am a good boy\nbut not a bad guy" 
print(a)

#\: It is used for printing ",' in the python.
b = "I am the best person in the \"world\"" #\" for printing ""
print(b)

#\\: It is for printing backslash in python.
c = "Earth is \\flat" 
print(c)

#\t: It is for printing tab in python.

d = "I will go zoo \t today" #it will give 4 space like tab
print(d)

